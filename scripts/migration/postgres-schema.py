"""Compile a greenfield PostgreSQL baseline from only the repository's SQLite migrations."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sqlite3

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "database/postgres"
IDENTIFIER = r'[a-zA-Z_][a-zA-Z_0-9]*'


def sha(text):
    return hashlib.sha256(text.encode()).hexdigest()


def fields(sql):
    """Split top-level table definitions, preserving quoted values and nested checks."""
    result, start, depth, quoted = [], 0, 0, False
    for index, char in enumerate(sql):
        if char == "'":
            quoted = not quoted
        elif not quoted:
            if char == '(':
                depth += 1
            elif char == ')':
                depth -= 1
            elif char == ',' and depth == 0:
                result.append(sql[start:index].strip())
                start = index + 1
    result.append(sql[start:].strip())
    return result


def expr(sql):
    # Reviewed dialect constructs in the source catalog. Leave strings and column bytes intact.
    sql = re.sub(r'\bIS\s+NOT\s+(?!NULL\b)', 'IS DISTINCT FROM ', sql, flags=re.I)
    sql = re.sub(r'\bIS\s+(?!(?:NOT|NULL|DISTINCT)\b)', 'IS NOT DISTINCT FROM ', sql, flags=re.I)
    sql = re.sub(r'\b(json_valid)\(([\w.]+)\)', r'(\2 IS JSON)', sql, flags=re.I)
    sql = re.sub(r'\bjson_array_length\(', 'pi_compat.json_length(', sql, flags=re.I)
    def extract(match):
        col, path = match.groups()
        path_parts = path.split('.')
        # Numeric JSON values stay typed: JSON string "100" must not pass an integer check.
        if path.endswith('Cents'):
            return f"({col}::jsonb #> '{{{','.join(path_parts)}}}')"
        return f"({col}::json #>> '{{{','.join(path_parts)}}}')"
    sql = re.sub(r"json_extract\(([\w.]+),\s*'\$\.([\w.]+)'\)", extract, sql, flags=re.I)
    sql = re.sub(r"(\(NEW\.calculation_json::jsonb #> '[^']+'\)) IS DISTINCT FROM (NEW\.\w+)", r'\1 IS DISTINCT FROM to_jsonb(\2)', sql)
    sql = re.sub(r"(\(NEW\.calculation_json::jsonb #> '[^']+'\)) IS DISTINCT FROM (\(SELECT c\..*?WHERE c.id=NEW.adjusts_charge_id\))", r'\1 IS DISTINCT FROM to_jsonb(\2)', sql, flags=re.S)
    sql = re.sub(r'\b(strftime|julianday)\(', lambda m: 'pi_compat.' + m[1].lower() + '(', sql, flags=re.I)
    sql = re.sub(r'\bINSTR\(', 'strpos(', sql, flags=re.I)
    sql = re.sub(r'lower\(hex\(randomblob\(16\)\)\)', "replace(gen_random_uuid()::text, '-', '')", sql, flags=re.I)
    sql = re.sub(r'\(([\w.]+ IS NOT NULL)\)(?=\s*\+)', r'(\1)::integer', sql, flags=re.I)
    sql = re.sub(r'\+\s*\(([\w.]+ IS NOT NULL)\)', r'+ (\1)::integer', sql, flags=re.I)
    sql = re.sub(r'\bCURRENT_TIMESTAMP\b', "to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')", sql, flags=re.I)
    sql = re.sub(r'\browid\b', 'pi_rowid', sql, flags=re.I)
    sql = re.sub(r'\bLIKE\b', 'ILIKE', sql, flags=re.I)
    sql = re.sub(r'\bAS INTEGER\b', 'AS BIGINT', sql, flags=re.I)
    globs = {'????-??': '^....-..$', 'acct_*': '^acct_.*$', '[A-Z][A-Z][A-Z]-[0-9][0-9][0-9]': '^[A-Z][A-Z][A-Z]-[0-9][0-9][0-9]$'}
    sql = re.sub(r"\bGLOB\s+'([^']+)'", lambda m: "~ '" + globs[m[1]] + "'", sql, flags=re.I)
    return sql


def create_table(name, sql, columns):
    inner = re.fullmatch(r'CREATE TABLE\s+["\w]+\s*\((.*)\)\s*(?:STRICT)?', sql.strip(), re.I | re.S)[1]
    definitions = []
    for definition in fields(inner):
        if re.match(r'FOREIGN\s+KEY', definition, re.I):
            continue  # All FKs are installed and validated after tables/unique indexes exist.
        definition = re.sub(r'\s+REFERENCES\s+"?\w+"?\s*\([^)]+\)(?:\s+ON\s+(?:UPDATE|DELETE)\s+(?:NO ACTION|RESTRICT|SET NULL|CASCADE|SET DEFAULT))*', '', definition, flags=re.I)
        definition = re.sub(r'\s+DEFERRABLE INITIALLY DEFERRED', '', definition, flags=re.I)
        if re.search(r'\bCOLLATE NOCASE\b', definition, re.I):
            definition = re.sub(r'\bTEXT\b', 'public.citext', definition, count=1, flags=re.I)
            definition = re.sub(r'\s+COLLATE NOCASE\b', '', definition, flags=re.I)
        definition = re.sub(r'^("?\w+"?\s+)INTEGER\b', r'\1BIGINT', definition, flags=re.I)
        if re.match(r'"?\w+"?\s+BIGINT PRIMARY KEY', definition, re.I):
            definition = re.sub(r'BIGINT PRIMARY KEY', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', definition, flags=re.I)
        definitions.append(expr(definition))
    if name == 'approvals':
        definitions.append('pi_rowid bigint GENERATED ALWAYS AS IDENTITY UNIQUE')
    return f'CREATE TABLE {name} (\n  ' + ',\n  '.join(definitions) + '\n);'


def trigger_sql(name, physical, sql, query_checks):
    pattern = rf'CREATE TRIGGER\s+\w+\s+(BEFORE|AFTER)\s+(INSERT|DELETE|UPDATE(?:\s+OF\s+[\w,\s]+?)?)\s+ON\s+({IDENTIFIER})\s*(?:WHEN\s+(.+?))?\s*BEGIN\s+(.+);\s*END'
    match = re.fullmatch(pattern, sql.strip(), re.I | re.S)
    if not match:
        raise ValueError(f'Unknown trigger shape: {name}')
    timing, event, table, when, body = match.groups()
    lines = []
    def check(statement):
        # Parse every trigger query against real PostgreSQL column/record types in CI.
        # The source has a lower-case relation alias "old" as well as OLD trigger records.
        statement = statement.replace('NEW.', '($1).').replace('OLD.', '($2).')
        query_checks.append(f'-- {name}\nPREPARE guard_query ({table}, {table}) AS {statement};\nDEALLOCATE guard_query;')
    # A SQLite WHEN can contain subqueries, so evaluate it inside the function.
    if when:
        check(f'SELECT 1 WHERE {expr(when)}')
        lines.append(f'IF ({expr(when)}) IS NOT TRUE THEN RETURN {"OLD" if event == "DELETE" else "NEW"}; END IF;')
    for raw in body.split(';'):
        statement = raw.strip()
        cte = ''
        if statement.upper().startswith('WITH RECURSIVE'):
            cte, statement = re.split(r'(?=SELECT RAISE\b)', statement, maxsplit=1, flags=re.I)
        guard = re.fullmatch(r"SELECT\s+RAISE\(\s*ABORT\s*,\s*'([^']+)'\s*\)(?:\s+WHERE\s+(.+))?", statement, re.I | re.S)
        case = re.fullmatch(r"SELECT\s+CASE\s+WHEN\s+(.+)\s+THEN\s+RAISE\(\s*ABORT\s*,\s*'([^']+)'\s*\)\s+END", statement, re.I | re.S)
        if guard or case:
            code, condition = guard.groups() if guard else case.groups()[::-1]
            message = f"RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = '{code}';"
            if condition:
                condition = expr(condition)
                if cte:
                    condition = f'({expr(cte)} SELECT ({condition}))'
                check(f'SELECT 1 WHERE {condition}')
                lines.extend([f'IF ({condition}) THEN', f'  {message}', 'END IF;'])
            else:
                lines.append(message)
        elif re.match(r'(INSERT|UPDATE)\s', statement, re.I):
            check(expr(statement))
            lines.append(expr(statement) + ';')
        else:
            raise ValueError(f'Unhandled statement in {name}: {statement}')
    lines.append('RETURN ' + ('OLD' if event.upper() == 'DELETE' else 'NEW') + ';')
    body_text = '\n'.join('  ' + line for line in lines)
    return f'-- {name}\nCREATE FUNCTION pi_compat.{name}() RETURNS trigger LANGUAGE plpgsql AS $$\n#variable_conflict use_column\nBEGIN\n{body_text}\nEND $$;\nCREATE TRIGGER {physical} {timing} {event} ON {table}\n  FOR EACH ROW EXECUTE FUNCTION pi_compat.{name}();'


def compile_schema():
    db = sqlite3.connect(':memory:')
    clock = sqlite3.connect(':memory:')
    def source_strftime(fmt, value, *modifiers):
        args = (fmt, '2100-11-23T14:21:32.473Z' if value == 'now' else value, *modifiers)
        return clock.execute('SELECT strftime(' + ','.join('?' * len(args)) + ')', args).fetchone()[0]
    db.create_function('strftime', -1, source_strftime)
    db.create_function('current_timestamp', 0, lambda: '2100-11-23 14:21:32')
    sources = []
    for path in sorted((ROOT / 'database/migrations').glob('*.sql')):
        sql = path.read_text()
        db.executescript(sql)
        sources.append({'migration': path.name, 'sha256': sha(sql)})
    catalog = db.execute("SELECT type,name,tbl_name,sql FROM sqlite_schema WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid").fetchall()
    tables = [(n,s) for t,n,_,s in catalog if t == 'table']
    indexes = [(n,s) for t,n,_,s in catalog if t == 'index']
    triggers = [(n,s) for t,n,_,s in catalog if t == 'trigger']
    if len(tables)+len(indexes)+len(triggers) != len(catalog):
        raise ValueError('Unsupported catalog object')
    sections = ['-- Generated from pristine repository migrations. See scripts/migration/postgres-schema.py.', (TARGET/'support.sql').read_text().rstrip()]
    manifest = {'source_migrations': sources, 'tables': {}, 'indexes': {}, 'triggers': {}}
    constraints = []
    for name, sql in tables:
        columns = [c[1] for c in db.execute(f'PRAGMA table_info({name})')]
        sections.append(create_table(name, sql, columns))
        fk_groups = {}
        for fid, _, parent, col, dest, update, delete, _ in db.execute(f'PRAGMA foreign_key_list({name})'):
            group = fk_groups.setdefault(fid, {'parent':parent, 'columns':[], 'references':[], 'update': update, 'delete': delete})
            group['columns'].append(col)
            group['references'].append(dest)
        for g in fk_groups.values():
            g['deferred'] = bool(re.search(r'\b' + g['columns'][0] + r'\s+\w+\s+REFERENCES\s+\w+\([^)]+\)\s+DEFERRABLE INITIALLY DEFERRED', sql, re.I))
            deferral = ' DEFERRABLE INITIALLY DEFERRED' if g['deferred'] else ''
            constraints.append(f"ALTER TABLE {name} ADD FOREIGN KEY ({','.join(g['columns'])}) REFERENCES {g['parent']} ({','.join(g['references'])}) ON UPDATE {g['update']} ON DELETE {g['delete']}{deferral};")
        manifest['tables'][name] = {'columns': columns, 'foreign_keys': list(fk_groups.values())}
    for name, sql in indexes:
        sections.append(expr(sql) + ';')
        manifest['indexes'][name] = {'unique': bool(re.match(r'CREATE UNIQUE', sql, re.I)), 'partial': bool(re.search(r'\bWHERE\b', sql, re.I))}
    # The pristine source replay contains only release-shipped seed rows, never a customer export.
    for name, _ in tables:
        cols = manifest['tables'][name]['columns']
        projection = ','.join(f'quote("{c}")' for c in cols)
        records = db.execute(f'SELECT {projection} FROM "{name}" ORDER BY rowid').fetchall()
        manifest['tables'][name]['seed_rows'] = len(records)
        if records:
            values = ',\n  '.join('(' + ','.join(row) + ')' for row in records)
            values = values.replace("'2100-11-23T14:21:32.473Z'", "pi_compat.strftime('%Y-%m-%dT%H:%M:%fZ','now')").replace("'2100-11-23 14:21:32'", expr('CURRENT_TIMESTAMP'))
            sections.append(f"INSERT INTO {name} ({','.join(cols)}) VALUES\n  {values};")
    sections.extend(constraints)
    # PostgreSQL orders same-event triggers alphabetically. Encode source newest-first order.
    checks = []
    for reverse_order, (name, sql) in enumerate(reversed(triggers)):
        physical = f'pi_{reverse_order:04d}_{name}'[:63]
        sections.append(trigger_sql(name, physical, sql, checks))
        manifest['triggers'][name] = physical
    for name, _ in tables:
        sections.append(f'CREATE TRIGGER pi_serialize_write BEFORE INSERT OR UPDATE OR DELETE ON {name} FOR EACH STATEMENT EXECUTE FUNCTION pi_compat.writer_lock();')
    return '\n\n'.join(sections) + '\n', json.dumps(manifest, indent=2) + '\n', '\n'.join(checks)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--trigger-checks', action='store_true', help='Print PostgreSQL PREPARE statements for every trigger expression')
    args = parser.parse_args()
    sql, manifest, checks = compile_schema()
    if args.trigger_checks:
        print(checks)
        raise SystemExit(0)
    for name, data in zip(['migrations/0001_platform.sql','source-catalog.json'], [sql, manifest]):
        path = TARGET / name
        if args.check:
            if path.read_text() != data:
                raise SystemExit(f'{path.name} differs from source migrations')
        else:
            path.write_text(data)
