-- Dual contractor-payment models. This is a reconciliation register, not a trust account.
-- No Stripe transfer, charge or bank payout occurs from this migration.
CREATE TABLE contractor_payment_plans (
 id TEXT PRIMARY KEY,
 work_order_id TEXT NOT NULL UNIQUE REFERENCES work_orders(id),
 client_id TEXT NOT NULL REFERENCES clients(id),
 property_id TEXT NOT NULL REFERENCES properties(id),
 contractor_id TEXT NOT NULL REFERENCES contractors(id),
 mode TEXT NOT NULL CHECK(mode IN ('platform_collect','payer_direct')),
 gross_cents INTEGER NOT NULL CHECK(gross_cents>0 AND gross_cents<=100000000),
 platform_fee_cents INTEGER NOT NULL DEFAULT 0 CHECK(platform_fee_cents>=0 AND platform_fee_cents<gross_cents),
 currency TEXT NOT NULL DEFAULT 'AUD' CHECK(currency='AUD'),
 quote_reference TEXT NOT NULL,
 invoice_reference TEXT NOT NULL,
 approval_id TEXT NOT NULL REFERENCES approvals(id),
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN (
  'draft','awaiting_checkout','checkout_open','funded','release_approved','transfer_initiated','transfer_created','transfer_review','reversed',
  'external_due','external_reported','external_verified','failed','disputed','cancelled')),
 payer_approved_by TEXT REFERENCES users(id),
 payer_approved_at TEXT,
 payer_authority_reference TEXT,
 checkout_session_id TEXT UNIQUE,
 stripe_payment_intent_id TEXT UNIQUE,
 stripe_charge_id TEXT,
 checkout_url TEXT,
 stripe_transfer_id TEXT UNIQUE,
 recipient_account_id TEXT,
 completion_reference TEXT,
 release_approved_by TEXT REFERENCES users(id),
 release_approved_at TEXT,
 external_payment_reference TEXT,
 external_reported_by TEXT REFERENCES users(id),
 external_reported_at TEXT,
 external_verified_by TEXT REFERENCES users(id),
 external_verified_at TEXT,
 external_verification_reference TEXT,
 transfer_initiated_by TEXT REFERENCES users(id),
 transfer_initiated_at TEXT,
 last_actor_id TEXT REFERENCES users(id),
 version INTEGER NOT NULL DEFAULT 1 CHECK(version>0),
 created_at TEXT NOT NULL,
 updated_at TEXT NOT NULL,
 CHECK(mode='platform_collect' OR (platform_fee_cents=0 AND checkout_session_id IS NULL AND stripe_transfer_id IS NULL)),
 CHECK(status NOT IN ('awaiting_checkout','checkout_open','funded','release_approved','transfer_initiated','transfer_created','transfer_review','reversed','disputed') OR mode='platform_collect'),
 CHECK(status NOT IN ('external_due','external_reported','external_verified') OR mode='payer_direct')
) STRICT;
CREATE INDEX contractor_payment_plans_scope ON contractor_payment_plans(client_id,property_id,created_at);
CREATE INDEX contractor_payment_plans_status ON contractor_payment_plans(status,mode);
CREATE TABLE contractor_connect_recipients (
 contractor_id TEXT PRIMARY KEY REFERENCES contractors(id),
 stripe_account_id TEXT NOT NULL UNIQUE CHECK(stripe_account_id GLOB 'acct_*'),
 status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','verified','disabled')),
 identity_verification_reference TEXT,
 identity_verified_by TEXT REFERENCES users(id),
 identity_verified_at TEXT,
 recorded_by TEXT NOT NULL REFERENCES users(id),
 created_at TEXT NOT NULL,
 updated_at TEXT NOT NULL,
 CHECK(status != 'verified' OR (identity_verification_reference IS NOT NULL AND identity_verified_by IS NOT NULL AND identity_verified_at IS NOT NULL))
) STRICT;
-- Immutable financial state changes, generated by a trigger in the same transaction.
CREATE TABLE contractor_payment_events (
 id TEXT PRIMARY KEY,
 plan_id TEXT NOT NULL REFERENCES contractor_payment_plans(id),
 from_status TEXT,
 to_status TEXT NOT NULL,
 actor_id TEXT,
 event_reference TEXT,
 created_at TEXT NOT NULL
) STRICT;
CREATE TRIGGER contractor_payment_events_no_update BEFORE UPDATE ON contractor_payment_events BEGIN SELECT RAISE(ABORT,'AUDIT_IMMUTABLE'); END;
CREATE TRIGGER contractor_payment_events_no_delete BEFORE DELETE ON contractor_payment_events BEGIN SELECT RAISE(ABORT,'AUDIT_IMMUTABLE'); END;
CREATE TRIGGER contractor_payment_insert_event AFTER INSERT ON contractor_payment_plans BEGIN
 INSERT INTO contractor_payment_events(id,plan_id,from_status,to_status,actor_id,event_reference,created_at)
 VALUES('cpe_'||lower(hex(randomblob(16))),NEW.id,NULL,NEW.status,NEW.last_actor_id,NEW.invoice_reference,NEW.created_at);
END;
CREATE TRIGGER contractor_payment_status_event AFTER UPDATE OF status ON contractor_payment_plans WHEN OLD.status!=NEW.status BEGIN
 INSERT INTO contractor_payment_events(id,plan_id,from_status,to_status,actor_id,event_reference,created_at)
 VALUES('cpe_'||lower(hex(randomblob(16))),NEW.id,OLD.status,NEW.status,NEW.last_actor_id,COALESCE(NEW.external_verification_reference,NEW.stripe_transfer_id,NEW.external_payment_reference,NEW.checkout_session_id,NEW.payer_authority_reference,NEW.quote_reference),NEW.updated_at);
END;
-- One receipt per Stripe event per endpoint; no raw PII or signature payload retained.
CREATE TABLE contractor_connect_webhook_receipts (
 event_id TEXT PRIMARY KEY,
 source TEXT NOT NULL CHECK(source IN ('checkout','platform','recipients')),
 event_type TEXT NOT NULL,
 stripe_object_id TEXT,
 created_at TEXT NOT NULL
) STRICT;
CREATE TRIGGER contractor_connect_webhook_receipts_no_update BEFORE UPDATE ON contractor_connect_webhook_receipts BEGIN SELECT RAISE(ABORT,'AUDIT_IMMUTABLE'); END;
CREATE TRIGGER contractor_connect_webhook_receipts_no_delete BEFORE DELETE ON contractor_connect_webhook_receipts BEGIN SELECT RAISE(ABORT,'AUDIT_IMMUTABLE'); END;